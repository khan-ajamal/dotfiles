vim.opt.number = true        -- show line numbers
vim.opt.relativenumber = true

vim.opt.tabstop = 4          -- a tab character displays as 4 columns
vim.opt.softtabstop = 4      -- 4 spaces inserted/deleted per Tab/Backspace
vim.opt.shiftwidth = 4       -- 4 spaces for auto-indent and >> 
vim.opt.expandtab = true     -- insert spaces instead of a tab character

vim.opt.ignorecase = true    -- case-insensitive search...
vim.opt.smartcase = true     -- ...unless you type a capital letter
vim.opt.clipboard = "unnamedplus"  -- yank to system clipboard
vim.opt.termguicolors = true -- 24-bit color

